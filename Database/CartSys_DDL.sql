CREATE TRIGGER TRG_ITENSVENDA_BI FOR ITENS_VENDA
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = NEXT VALUE FOR SEQ_ITENS_VENDA;
END^

CREATE TRIGGER TRG_LOGACESSO_BI FOR LOG_ACESSO
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = NEXT VALUE FOR SEQ_LOG_ACESSO;
