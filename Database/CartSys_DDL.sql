CREATE TRIGGER TRG_MOVFIN_BI FOR MOVIMENTO_FINANCEIRO
ACTIVE BEFORE INSERT POSITION 0
AS
BEGIN
  IF (NEW.ID IS NULL) THEN
    NEW.ID = NEXT VALUE FOR SEQ_MOVIMENTO_FINANCEIRO;
END^

SET TERM ; ^

